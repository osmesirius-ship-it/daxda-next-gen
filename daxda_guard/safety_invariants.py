def get_active_invariants() -> list[SafetyInvariant]:
    return [i for i in REGISTRY if i.status != InvariantStatus.VIOLATED]


def get_violated_invariants() -> list[SafetyInvariant]:
    return [i for i in REGISTRY if i.status == InvariantStatus.VIOLATED]


def print_invariant_summary():
    counts = {}
    for inv in REGISTRY:
        counts[inv.status.value] = counts.get(inv.status.value, 0) + 1

    print("=" * 82)
    print("   DAXDA SAFETY INVARIANT REGISTRY — SUMMARY")
    print("=" * 82)
    print(f"   Total invariants: {len(REGISTRY)}")
    for status, count in sorted(counts.items()):
        marker = "🔴" if status == "VIOLATED" else ("✅" if status == "ACTIVE" else "⚠ ")
        print(f"   {marker} {status:<15}: {count}")
    print()
    print(f"   {'ID':<10} {'Status':<12} {'Failure Class':<30} {'Title'}")
    print(f"   {'-'*10} {'-'*12} {'-'*30} {'-'*40}")
    for inv in REGISTRY:
        marker = "🔴" if inv.status == InvariantStatus.VIOLATED else (
                 "✅" if inv.status == InvariantStatus.ACTIVE else "⚠ ")
        print(f"   {marker}{inv.id:<9} {inv.status.value:<12} {inv.failure_class:<30} {inv.title[:40]}")
    print("=" * 82)


if __name__ == "__main__":
    print_invariant_summary()

    violated = get_violated_invariants()
    if violated:
        print(f"\n🔴 RELEASE BLOCKED: {len(violated)} violated invariant(s)")
        for v in violated:
            print(f"   {v.id}: {v.title}")
    else:
        print("\n✅ No violated invariants — release not blocked by invariant registry.")
